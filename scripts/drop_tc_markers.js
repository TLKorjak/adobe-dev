function tc2sec(tc){ const p=tc.split(":"); return (+p[0])*3600+(+p[1])*60+(+p[2])+(+p[3])/25; }

const existing = await markers.getMarkers();
const cleared = existing ? existing.length : 0;
if (cleared) {
  await project.lockedAccess(function(){
    project.executeTransaction(function(tx){
      for (let i=0;i<existing.length;i++) tx.addAction(markers.createRemoveMarkerAction(existing[i]));
    }, "Bridge: clear markers");
  });
}

const seen = {};
const items = [];
let skippedRange = 0, skippedDup = 0;
for (let i=0;i<tcs.length;i++){
  let pos = tc2sec(tcs[i]) - zero;
  if (pos < 0) pos = 0;
  if (pos > endS) { skippedRange++; continue; }
  const key = Math.round(pos*25);
  if (seen[key]) { skippedDup++; continue; }
  seen[key] = true;
  items.push({ pos: pos, name: tcs[i] });
}

let added = 0;
await project.lockedAccess(function(){
  project.executeTransaction(function(tx){
    for (let i=0;i<items.length;i++){
      const tt = ppro.TickTime.createWithSeconds(items[i].pos);
      tx.addAction(markers.createAddMarkerAction(items[i].name, T, tt, z, ""));
      added++;
    }
  }, "Bridge: add transcript tc markers");
});

const after = await markers.getMarkers();
return { sequence: seq.name, zeroPointSec: zero, endSec: endS,
  sourceTimecodes: tcs.length, cleared: cleared,
  skippedOutOfRange: skippedRange, skippedDuplicateFrame: skippedDup,
  markersAdded: added, markersNow: after.length };
